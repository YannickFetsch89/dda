## Samstag, 28. November

Der Samstag ist der vollste Tag der Woche.

In der Merkur Spiel-Arena in Stockum steigt die **WBC World Heavyweight Championship**: Der Bochumer Agit Kabayel verteidigt zum ersten Mal seinen Weltmeistertitel, bisher mit 27 Siegen aus 27 Kämpfen. Gegner Nelson Hysa ist ebenfalls ungeschlagen, 23 seiner 25 Siege holte er durch K.-o. Zwei unbesiegte Schwergewichtler im Ring – das ist auch für Gelegenheits-Boxfans ein Termin.

Für Familien geht es nach Oberbilk: Die **Lichterkinder** kommen mit ihrer „Millionen Sterne Tour“ in die Mitsubishi Electric Halle. Viele Kinder kennen die Tanz-, Bewegungs- und Lernlieder schon aus Kita und Kinderzimmer, live spielt eine siebenköpfige Band – Singen, Tanzen und Klatschen sind ausdrücklich erwünscht. Für viele Kinder ist es das erste Konzert.

Zum ersten Mal in Düsseldorf: Der **Veihnachtsmarkt**, ein veganer Weihnachtsmarkt, verwandelt am ersten Adventswochenende die Jugendkirche in einen Ort für veganen Advent – mit Kreativmarkt, Familienprogramm und Live-Performances. Mit dabei sind unter anderem Schmuck, Kunst und Kunsthandwerk sowie gemeinnützige Vereine, am Samstag gibt es außerdem Essen von Sel la vie.

Wer es lieber kölsch-rockig mag: [BAP](/event/musik/bap-psd-bank-dome-2026-11-28) spielen im PSD Bank Dome.

