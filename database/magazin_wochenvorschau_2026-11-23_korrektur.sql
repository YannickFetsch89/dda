## Dienstag, 24. November

Am Dienstag lohnt sich der Weg nach Oberbilk: **The Script** kommen mit ihrer „Man In The Arena“-Tour in die Mitsubishi Electric Halle. Die irische Pop-Rock-Band um Danny O’Donoghue bringt ihre größten Hits und neue Songs mit – Hymnen wie „Hall Of Fame“ und „Breakeven“ inklusive. Als Special Guest ist James Morrison dabei. Auch hier gilt: Wegen der Spursperrung auf der Siegburger Straße etwas mehr Zeit für die Anreise einplanen.

