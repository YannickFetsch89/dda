## Montag, 23. November

Die Woche startet gleich mit drei sehr unterschiedlichen Abenden.

Im Kom(m)ödchen in der Altstadt packen **Fritz & Hermann** aus: Rainer Pause und Norbert Alich bringen ihr Weihnachtsspezial auf die Bühne, mit alten und neuen Liedern, ein paar Vorurteilen und Antworten auf Fragen, die niemand gestellt hat. Rheinisches Kabarett, das die Adventszeit nicht allzu ernst nimmt.

Im Tanzhaus NRW in Flingern feiert **take-off: Junger Tanz Düsseldorf** zwanzig Jahre Tanz für junge Menschen. Das Festival schaut zurück auf zwei Jahrzehnte und fragt zugleich, wohin es gehen soll – mit Gastspielen, Workshops, Gesprächen und Beiträgen junger Gruppen und Compagnien.

Wer lieber zuhört und mitdenkt: Im FFT in Stadtmitte spricht Dirk Quadflieg im Rahmen der Vortragsreihe der Kunstakademie über **„Die KI und wir“** – ein Thema, an dem gerade niemand vorbeikommt.

