## Die Weihnachtsmarkt-Saison hat begonnen

Seit letzter Woche haben die Weihnachtsmärkte in der Innenstadt geöffnet – vom [Altstadt-Markt](/guides/weihnachtsmaerkte/altstadt-markt-altstadt) über den [Märchen-Markt am Schadowplatz](/guides/weihnachtsmaerkte/maerchen-markt-stadtmitte) und [The Winter Village](/guides/weihnachtsmaerkte/the-winter-village-stadtmitte) auf der Kö bis zur [Weihnachtspromenade am Rhein](/guides/weihnachtsmaerkte/weihnachtspromenade-am-rhein-altstadt). Dazu kommen die Eisbahn [Kö on Ice](/guides/weihnachtsmaerkte/koe-on-ice-deg-winterwelt-stadtmitte) und das [Riesenrad auf dem Burgplatz](/guides/weihnachtsmaerkte/riesenrad-wheel-of-vision-altstadt).

Auch außerhalb der Innenstadt geht es los: Vor [Schloss Benrath](/guides/weihnachtsmaerkte/weihnachtsmarkt-schloss-benrath) steht an den Adventswochenenden ein Markt mit Kunsthandwerk, ab Dienstag öffnet der [Weihnachtszauber im Areal Böhler](/guides/weihnachtsmaerkte/weihnachtszauber-areal-boehler-heerdt), und auf der [Nordstraße](/guides/weihnachtsmaerkte/weihnachtszeit-nordstrasse-pempelfort) in Pempelfort ist Advent im Viertel.

