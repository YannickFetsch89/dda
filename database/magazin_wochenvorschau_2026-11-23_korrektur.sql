## Mittwoch, 25. November

Im Großen Haus des Schauspielhauses steht **„Verbrennung“** auf dem Programm – eine Theateraufführung mit anschließender Podiumsdiskussion. Das Format ist ideal für alle, die nach dem Stück nicht direkt nach Hause wollen, sondern das Gesehene gleich besprechen möchten. Mehr Details zum Inhalt liegen uns nicht vor, die Event-Karte zeigt euch alles Wichtige zum Termin.

