## Donnerstag, 26. November

Der Donnerstag hat gleich mehrere starke Optionen.

Im Capitol Theater in Flingern spielen **Shkodra Elektronike**: Das albanische Duo Kolb Laca und Beatri Gjergji überträgt traditionelle Lieder ihrer Heimatstadt Shkodra in einen elektronischen, alternativen Sound. Spätestens seit dem achten Platz beim ESC in Basel kennt ein großes Publikum diesen Mix.

Im Kom(m)ödchen improvisieren die **Gude Leude** einen Weihnachtsabend, der besinnlich werden soll – und es vermutlich nicht wird. Ihr liefert per Regie-Anweisung Anekdoten, Onkel-Sprüche und Lieblingslieder, der Rest entsteht live. Achtung: Die Vorstellung von Lars Reichow am selben Ort fällt laut Veranstalter aus.

Wer Lust auf Gründer:innen-Luft hat, geht zum **Honeymoon Startup Pitch** ins Beehive in Pempelfort: fünf Startups, je fünf Minuten Bühne, danach eine harte Fragerunde, Jury-Entscheidung und Networking bei Snacks und Drinks.

R&B-Fans haben außerdem eine Alternative: [Bryson Tiller und Majid Jordan](/event/sonstiges/bryson-tiller-majid-jordan-in-duesseldorf-mitsubishi-electric-halle-2026-11-26) kommen gemeinsam in die Mitsubishi Electric Halle.

